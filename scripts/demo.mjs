// Produces example outputs for review WITHOUT touching Lea's real queue:
//  - docs/examples/maya-handoff-<scenario>.md : each NATEA scenario approved by the DEMO HARNESS (not Lea)
//  - docs/examples/scenario-outputs.md        : classification, facts, missing info, brief, actions, draft, quality
// Uses a throwaway DB. Usage: npm run demo
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { openDb } from '../src/db.js';
import { seedBusinesses, SAMPLE_INQUIRIES } from '../src/businesses.js';
import { createMockAdapter } from '../src/adapters/mock.js';
import { WorkflowEngine, submitRequest, reviewRun, runDetail } from '../src/graph.js';

const out = path.resolve('docs/examples');
fs.mkdirSync(out, { recursive: true });
const store = openDb(path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'demo-')), 'demo.db'));
seedBusinesses(store);
const adapter = createMockAdapter();
const engine = new WorkflowEngine({ store, adapter });
const HARNESS = 'DEMO HARNESS (simulated approval — not Lea)';
const md = ['# NATEA scenario outputs (mock adapter)', '', '> **SAMPLE DATA** (fictional clients) · **SIMULATED** outputs from the deterministic mock adapter · generated by `npm run demo`', ''];

for (const s of SAMPLE_INQUIRIES.natea) {
  const run = submitRequest(store, 'natea', { title: s.title, body: s.body, contact: s.contact, isSample: true, sampleKey: s.key }, adapter);
  await engine.runUntilIdle();
  const pre = runDetail(store, 'natea', run.id);
  const cls = pre.steps.find((x) => x.step === 'classify').output;
  const d = pre.drafts.at(-1);
  const b = d.content.brief;
  md.push(`## ${s.title}`, '', '**Inquiry**', '', '```text', s.body, '```', '');
  md.push(`**1. Classification:** ${cls.label} (\`${cls.category}\`, confidence ${cls.confidence}) — ${cls.rationale}`, '');
  md.push('**2. Known facts** (quoted from the inquiry)', '', ...b.known_facts.map((f) => `- ${f.label}: ${f.value} — _"${f.evidence}"_`), '');
  md.push('**Missing information**', '', ...b.missing_info.map((m) => `- ${m.label}`), '');
  md.push(`**3. Structured client brief:** ${b.summary}`, '', ...b.observations.map((o) => `- ${o.label}: ${o.value}`), '');
  md.push('**4. Proposed next actions**', '', ...b.next_actions.map((a) => `- ${a}`), '');
  md.push(`**5. Response draft (v${d.version})** — Subject: ${d.content.response_draft.subject}`, '', '```text', d.content.response_draft.body, '```', '');
  md.push(`**6. Quality review:** ${d.quality.passed ? 'PASSED' : 'FAILED'} (${Math.round(d.quality.score * 100)}%)`, '', ...d.quality.checks.map((c) => `- ${c.passed ? '✓' : '✕'} ${c.label} — ${c.detail}`), '');
  reviewRun(store, 'natea', run.id, { action: 'approve', decidedBy: HARNESS });
  await engine.runUntilIdle();
  const done = runDetail(store, 'natea', run.id);
  const file = path.join(out, `maya-handoff-${s.key}.md`);
  fs.writeFileSync(file, `<!-- EXAMPLE: approved by ${HARNESS}. Lea's real queue still awaits her decisions. -->\n${done.handoff.markdown}`);
  md.push(`**7. Maya handoff after approval:** [${path.basename(file)}](./${path.basename(file)}) _(approval simulated by the demo harness)_`, '');
}
fs.writeFileSync(path.join(out, 'scenario-outputs.md'), md.join('\n'));
console.log(`Wrote ${out}/scenario-outputs.md and 3 example handoffs.`);
store.close();
